"""Generate shop-tier facts from the archived current-season operator catalogue."""

import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    source = json.loads(args.source.read_text(encoding="utf-8-sig"))
    rows = source["operators"]
    names = set()
    for row in rows:
        if (not row["name"] or row["name"] in names
                or row["tier"] not in range(1, 7) or row["price"] not in range(0, 7)):
            raise ValueError(f"Invalid operator fact: {row['name']}")
        names.add(row["name"])
    lines = [
        "#pragma once", "", "#include <array>", "#include <string_view>", "",
        "// Current-season PRTS/SquadPool snapshot, 2026-11-10; CC BY-NC-SA 3.0.",
        "// Generated by tools/SPA/generate_operator_catalogue.py; tiers are shop levels, not rarity.",
        "namespace asst::spa", "{", "struct OperatorCatalogueEntry", "{",
        "    std::string_view name;", "    int tier;", "    int price;",
        "    bool sale_has_side_effect;", "    bool trait_mentions_bench;", "};", "",
        f"inline constexpr std::array<OperatorCatalogueEntry, {len(rows)}> OperatorCatalogue {{{{",
    ]
    for row in rows:
        name = json.dumps(row["name"], ensure_ascii=False)
        sale_trigger = any(trigger in row.get("when", []) for trigger in ("售出时", "出售时"))
        trait = row.get("n", "") + row.get("e", "")
        bench_trait = any(word in trait for word in ("整备区", "备战区"))
        lines.append(f"    {{ {name}, {row['tier']}, {row['price']}, "
                     f"{str(sale_trigger).lower()}, {str(bench_trait).lower()} }},")
    lines += ["}};", "}", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
