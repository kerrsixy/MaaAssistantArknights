"""Generate Sequence I unlock and mode rules from the archived client model."""

import argparse
import json
from pathlib import Path
import re


UNLOCK_RULES = (
    (r"通关任意模拟(\d+)次解锁", "AnyWin"),
    (r"通关任意联合模拟(\d+)次解锁", "JointWin"),
    (r"通关【(标准模拟|险境模拟|绝境模拟|终极模拟)】解锁", "JointDifficultyWin"),
    (r"消耗资金累计达到(\d+)时解锁", "FundsSpent"),
    (r"累计出售任意干员达到(\d+)个解锁", "OperatorsSold"),
    (r"累计刷新调度中心(\d+)次解锁", "ShopRefreshed"),
    (r"累计获得任意装备(\d+)个解锁", "EquipmentAcquired"),
    (r"累计升级调度中心(\d+)次解锁", "ShopUpgraded"),
    (
        r"通关时的结算阵容中，包含(?:任意)?(?:(\d+)名)?【([^】]+)】干员解锁",
        "SettlementRoster",
    ),
    (r"累计获得(\d+)名【([^】]+)】干员解锁", "FactionRecruited"),
    (r"多场模拟中【([^】]+)】盟约累计(\d+)层解锁", "FactionLayers"),
)
MODE_GROUPS = (
    {"mode_single_funny"},
    {f"mode_single_{level}" for level in range(1, 21)},
    {"mode_multi_funny", "mode_multi_normal", "mode_multi_hard", "mode_multi_abyss"},
)


def unlock_rule(description):
    if description is None:
        return "Default", 0, ""
    for pattern, kind in UNLOCK_RULES:
        if match := re.fullmatch(pattern, description):
            if kind == "JointDifficultyWin":
                return kind, 1, match[1]
            if kind == "FactionLayers":
                return kind, int(match[2]), match[1]
            return kind, int(match[1] or 1), match[2] if match.lastindex == 2 else ""
    raise ValueError(f"Unknown strategy unlock condition: {description!r}")


def mode_availability(mode_ids):
    disabled = set(mode_ids)
    if len(disabled) != len(mode_ids) or disabled - set.union(*MODE_GROUPS):
        raise ValueError(f"Unknown or duplicate disabled modes: {mode_ids!r}")
    # Keep exact rules. If a new season bans only some independent or joint
    # difficulty levels, explicitly extend the native schema before porting it.
    if any(disabled & group and not group <= disabled for group in MODE_GROUPS):
        raise ValueError(f"Partial mode ban is not representable: {mode_ids!r}")
    return tuple(not disabled & group for group in MODE_GROUPS)


def generate(catalogue):
    if catalogue["season"] != "act3autochess/V3_1":
        raise ValueError("Unexpected season")
    rows = sorted(catalogue["strategies"], key=lambda row: row["sortId"])
    ids = {row["bandId"] for row in rows}
    if len(rows) != 61 or len(ids) != len(rows):
        raise ValueError("Expected all 61 distinct strategies")
    kinds = ",\n    ".join(["Default", *(kind for _, kind in UNLOCK_RULES)])
    lines = [
        "#pragma once",
        "#include <array>",
        "#include <string_view>",
        "",
        "// Generated by tools/SPA/generate_strategy_unlock_catalogue.py from SPACombatData.json.",
        "namespace asst::spa",
        "{",
        "enum class StrategyUnlockKind",
        "{",
        f"    {kinds}",
        "};",
        "",
        "struct StrategyUnlockRule",
        "{",
        "    std::string_view id;",
        "    StrategyUnlockKind kind;",
        "    int count;",
        "    std::string_view prerequisite;",
        "    std::string_view description;",
        "    bool quick_available;",
        "    bool independent_available;",
        "    bool joint_available;",
        "};",
        "",
        f"inline constexpr std::array<StrategyUnlockRule, {len(rows)}> StrategyUnlockCatalogue {{{{",
    ]
    for row in rows:
        if (row["victorCount"], row["masterVictorCount"]) != (3, 6):
            raise ValueError(f"Changed victory thresholds for {row['bandId']}")
        kind, count, prerequisite = unlock_rule(row["unlockDesc"])
        words = map(
            lambda value: json.dumps(value, ensure_ascii=False),
            (row["bandId"], prerequisite, row["unlockDesc"] or ""),
        )
        identity, target, description = words
        available = ", ".join(
            str(value).lower() for value in mode_availability(row["inactiveModeIdList"])
        )
        lines.append(
            f"    {{ {identity}, StrategyUnlockKind::{kind}, {count}, {target}, {description}, {available} }},"
        )
    lines.extend(["}};", "}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    data = json.loads(args.source.read_text(encoding="utf-8-sig"))
    args.output.write_text(generate(data), encoding="utf-8")
