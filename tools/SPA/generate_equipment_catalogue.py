"""Keep current-season equipment descriptions and consumption facts in MaaCore."""

import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    rows = json.loads(args.source.read_text(encoding="utf-8-sig"))["equipment"]
    names = set()
    lines = [
        "#pragma once",
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        "// Current-season PRTS/SquadPool snapshot, 2026-11-10; CC BY-NC-SA 3.0.",
        "// Generated by tools/SPA/generate_equipment_catalogue.py.",
        "namespace asst::spa",
        "{",
        "struct EquipmentCatalogueEntry",
        "{",
        "    std::string_view name;",
        "    int tier;",
        "    int price;",
        "    std::string_view normal;",
        "    std::string_view advanced;",
        "    bool consumed;",
        "};",
        "",
        f"inline constexpr std::array<EquipmentCatalogueEntry, {len(rows)}> EquipmentCatalogue {{{{",
    ]
    for row in rows:
        if (
            not row["name"]
            or row["name"] in names
            or row["tier"] not in range(1, 7)
            or row["price"] not in range(0, 7)
        ):
            raise ValueError(f"Invalid equipment fact: {row['name']}")
        names.add(row["name"])
        text = row["n"] + row["e"]
        # This is an explicit catalogue property, not evidence of live use.
        consumed = "销毁" in text
        runtime_row = dict(row)
        # Preserve the archived initial-zero template. Catalogue prose cannot
        # stand in for the selected item's current, visually verified balance.
        if (
            row["name"] == "定期存折"
            and row.get("economy_kind") == "held_round_accumulation_then_redeem"
            and row["n"] == "装备时销毁，获得0资金（持有时每回合+1）"
        ):
            runtime_row["n"] = "装备时销毁，获得当前累计的资金（持有时每回合+1）"
        values = [
            json.dumps(runtime_row[key], ensure_ascii=False)
            for key in ("name", "n", "e")
        ]
        lines.append(
            f"    {{ {values[0]}, {row['tier']}, {row['price']}, "
            f"{values[1]}, {values[2]}, {str(consumed).lower()} }},"
        )
    lines += ["}};", "}", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
